struct chip8_mem {
    uint16_t seed;
    uint16_t address_register;
    uint16_t program_counter;
    uint8_t delay_timer;
    uint8_t sound_timer;
    uint16_t stack_pointer;
    uint16_t keyboard;
    uint8_t memory[RAM_SIZE];
    uint8_t rom[ROM_SIZE];
    uint8_t display[DISPLAY_SIZE];
};

struct chip8_instruction {
    uint16_t full_inst;
    uint8_t opcode;
    uint8_t n_value;
    uint8_t kk_value;
    uint8_t register_x;
    uint8_t register_y;
    uint16_t address;
};

